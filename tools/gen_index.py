"""Regenerate lib/README.md: one row per folder with its README, snippets per language and test files.

    python tools/gen_index.py
"""

from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LIB = ROOT / "lib"
LANGS = [("C++", ".cpp"), ("Java", ".java"), ("Rust", ".rs")]


def is_test(p: Path) -> bool:
    return p.name.startswith("test_") or p.stem.endswith("Test")


def title(readme: Path) -> str:
    for line in readme.read_text(encoding="utf-8").splitlines():
        if line.startswith("# "):
            return line[2:].strip()
    return ""


def main() -> None:
    rows = []
    for d in sorted([LIB, *(p for p in LIB.rglob("*") if p.is_dir())]):
        if d == LIB:
            continue
        files = [p for p in d.iterdir() if p.is_file()]
        rel = d.relative_to(LIB).as_posix()
        readme = d / "README.md"
        doc = f"[{title(readme) or 'README'}]({rel}/README.md)" if readme.exists() else ""
        counts = [str(sum(1 for p in files if p.suffix == ext and not is_test(p)) or "") for _, ext in LANGS]
        tests = sum(1 for p in files if is_test(p))
        depth = rel.count("/")
        name = ("&nbsp;" * 4 * depth) + f"`{d.name}/`"
        rows.append(f"| {name} | {doc} | {' | '.join(counts)} | {tests or ''} |")
    head = [
        "# Library index",
        "",
        "Generated by `python tools/gen_index.py`; do not edit by hand. Counts are the snippet files directly in each",
        "folder (not in subfolders); a technique folder normally has one README and its tests next to the code.",
        "",
        "| Folder | README | " + " | ".join(n for n, _ in LANGS) + " | Tests |",
        "|---|---|" + "---:|" * len(LANGS) + "---:|",
    ]
    (LIB / "README.md").write_text("\n".join(head + rows) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote lib/README.md ({len(rows)} folders)")


if __name__ == "__main__":
    main()
